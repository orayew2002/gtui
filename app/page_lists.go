package main

import "github.com/orayew2002/gtui"

func pageLists() gtui.Component {
	return gtui.Column("grow gap-1",
		cards(
			card("a", "tree",
				note("enter folds a branch, enter on a file opens it"),
				gtui.TreeView(gtui.TreeOptions{
					Roots: []gtui.TreeNode{{Label: "project", Open: true, Children: []gtui.TreeNode{
						{Label: "cmd", Children: []gtui.TreeNode{
							{Label: "main.go", Icon: "code"},
						}},
						{Label: "internal", Children: []gtui.TreeNode{
							{Label: "api.go", Icon: "code"},
						}},
						{Label: "README.md", Icon: "file"},
					}}},
					OnSelect: func(item gtui.TreeNode) { say("tree-out", "opened %s", item.Label) },
				}),
				out("tree-out", "nothing opened"),
			),
			card("b", "accordion and collapse",
				note("enter opens one section at a time"),
				gtui.Accordion("",
					gtui.Section{Title: "general", Open: true, Body: []gtui.Component{
						gtui.KeyValue("", [2]string{"theme", "dark"}, [2]string{"width", "120"}),
					}},
					gtui.Section{Title: "advanced", Body: []gtui.Component{
						gtui.Text("text-muted", "hidden until you open it"),
					}},
				),
				gtui.Collapse("", "Collapse is an Accordion of one", false,
					gtui.Text("text-muted", "handy for a single fold"),
				),
			),
		),
		cards(
			card("d", "scroll list",
				note("1000 rows, only the visible ones are built"),
				gtui.ScrollList("#big-list", 6, 1000, func(index int) gtui.Component {
					return gtui.Row("gap-1",
						gtui.Text("w-6 dim nowrap", "%04d", index),
						gtui.Text("grow truncate", "row number %d", index),
					)
				}).On("scroll", func(e *gtui.Event) { say("list-out", "first visible row is %s", e.Value) }),
				out("list-out", "↑↓ and ⇞⇟ scroll it"),
			),
			card("f", "rows, pairs and tags",
				note("Scrollbox keeps five rows inside three lines"),
				gtui.Scrollbox("focusable pr-1", 3,
					gtui.ListRow("", "disk-01", gtui.StatusDot("", "ok"), gtui.Text("nowrap", "ready")),
					gtui.ListRow("", "disk-02", gtui.StatusDot("", "busy"), gtui.Text("nowrap", "syncing")),
					gtui.ListRow("", "disk-03", gtui.StatusDot("", "down"), gtui.Text("nowrap", "offline")),
					gtui.ListItem("", "usb pool", "idle"),
					gtui.ListItem("", "nas-01", "idle"),
				),
				gtui.KeyValue("", [2]string{"framework", "gtui"}, [2]string{"license", "MIT"}),
				gtui.Row("gap-x-2 items-center flex-wrap",
					gtui.Tag("", "go", func(e *gtui.Event) { say("tag-out", "removed the go tag") }),
					gtui.Tag("", "tui", func(e *gtui.Event) { say("tag-out", "removed the tui tag") }),
					gtui.Chips("", "flexbox", "ansi"),
				),
				out("tag-out", "click the × on a tag"),
			),
		),
		cards(
			card("h", "plain lists",
				note("List stacks ListItem label and value pairs"),
				gtui.List("",
					gtui.ListItem("", "disk-01", "ready"),
					gtui.ListItem("", "disk-02", "verifying"),
					gtui.ListItem("", "disk-07", "failed"),
				),
				gtui.Divider("border-line"),
				gtui.Text("text-muted dim", "Divider draws the rule above"),
			),
			card("j", "static tree",
				note("Tree is the plain drawing, TreeView adds the clicking"),
				gtui.Tree("",
					gtui.TreeNode{Label: "pools", Open: true, Children: []gtui.TreeNode{
						{Label: "fast", Value: "2 disks", Icon: "disk"},
						{Label: "archive", Value: "10 disks", Icon: "disk"},
					}},
				),
			),
		),
		card("g", "timeline and steps",
			note("both take their colour from a kind, not a class"),
			gtui.Steps("", 1,
				gtui.StepItem{Title: "pick a disk", Note: "done"},
				gtui.StepItem{Title: "verify", Note: "running"},
				gtui.StepItem{Title: "restore"},
			),
			gtui.Timeline("",
				gtui.TimelineItem{Icon: "check", Kind: "ok", Title: "backup finished", Time: "09:12"},
				gtui.TimelineItem{Icon: "refresh", Kind: "busy", Title: "sync running", Time: "09:40", Body: "4 of 12 disks"},
			),
		),
	)
}
