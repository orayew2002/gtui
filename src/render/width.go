package render

func RuneWidth(r rune) int {
	switch {
	case r == 0:
		return 0
	case r < 0x20:
		return 0
	case r < 0x7f:
		return 1
	}

	if inRanges(r, zeroWidth) {
		return 0
	}
	if inRanges(r, doubleWidth) {
		return 2
	}
	return 1
}

func StringWidth(s string) int {
	for i := 0; i < len(s); i++ {
		if s[i] >= 0x80 {
			return wideStringWidth(s[i:]) + i
		}
	}
	return len(s)
}

func wideStringWidth(s string) int {
	w := 0
	for _, r := range s {
		w += RuneWidth(r)
	}
	return w
}

func TruncateWidth(s string, max int) (string, int) {
	if max <= 0 {
		return "", 0
	}

	w := 0
	for i, r := range s {
		rw := RuneWidth(r)
		if w+rw > max {
			return s[:i], w
		}
		w += rw
	}
	return s, w
}

type rng struct{ lo, hi rune }

func inRanges(r rune, table []rng) bool {
	lo, hi := 0, len(table)-1
	for lo <= hi {
		mid := (lo + hi) / 2
		switch {
		case r < table[mid].lo:
			hi = mid - 1
		case r > table[mid].hi:
			lo = mid + 1
		default:
			return true
		}
	}
	return false
}

